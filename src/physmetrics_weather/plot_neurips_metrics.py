#!/usr/bin/env python
"""Plotting & Visualization Script for Physics Metrics.

Reads long-format CSV files generated by `physmetrics-run` and time-series CSVs,
producing publication-ready figures for conservation drift, balance errors, kinetic
energy spectra, and effective resolution.

Ensemble / Probabilistic Support:
    Handles CSV outputs with `ensemble_member` columns automatically. Aggregates
    ensemble members by computing mean and standard deviation shading or individual
    realization trajectories.

Output Plots:
    1. ts_dry_mass_Eg.png       — Global dry air mass drift timeseries
    2. ts_water_mass_kg.png     — Global water mass drift timeseries
    3. ts_total_energy_J.png    — Global total energy drift timeseries
    4. ts_hydrostatic_rmse.png  — Hydrostatic balance error timeseries
    5. ts_geostrophic_rmse.png  — Geostrophic balance error timeseries
    6. neurips_table_*.png      — Summary tables
    7. spectra_ke_*.png         — Kinetic energy spectra for target leads
    8. lapse_rate_*.png         — Lapse rate distributions by region

Usage:
    physmetrics-plot --results-dir ./results --outdir ./plots
"""

